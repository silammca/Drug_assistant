    "Before answering, choose exactly ONE route.\n\n"

    "ROUTE 1 - DRUG SEARCH / GENERAL KNOWLEDGE -> call search_drugs.\n"
    "The question asks for general information about a medication, "
    "its uses, ingredients, dosage forms, or properties.\n"
    "Examples:\n"
    "  'What is paracetamol used for?' -> search_drugs\n"
    "  'Find medicines containing ibuprofen.' -> search_drugs\n"
    "  'What are the active ingredients in this medicine?' -> search_drugs\n"
    "  'Show me the available tablet forms of amoxicillin.' -> search_drugs\n"
    "  'Search for medicines used to treat allergies.' -> search_drugs\n\n"

